export function getNaesinPrompt(questionType: string, difficulty: string): string | null {
  const basePrompt = NAESIN_PROMPTS[questionType];
  if (!basePrompt) return null;

  const diffInstruction = DIFFICULTY_INSTRUCTIONS[difficulty as keyof typeof DIFFICULTY_INSTRUCTIONS] || DIFFICULTY_INSTRUCTIONS.medium;

  return basePrompt + "\n" + diffInstruction;
}
